# -*- coding: utf-8 -*-
"""Refait une illustration depuis son original (1024×1024) : un simple recadrage.

Les originaux se trouvent à plat dans assets/img-raw/{hsk1,hsk2}/ (dossier ignoré
par git et par le déploiement), issus des branches `raw-images` et `originaux`.
Un mot généré plusieurs fois a une version par fichier : « <mot>.<ext> » (v1),
« <mot>__v2.<ext> » (la correction qui lève l'ambiguïté), « __v3 »… ; l'image publiée
est le plus souvent la dernière. Le script recadre chaque version et garde celle
qui ressemble le plus à l'image publiée. (« <mot>__originaux.<ext> » : doublon
de nom entre les deux branches.)

Les anciens traitements (normalize_images.py, clean_images.py) détectaient le
sujet par sa saturation : tout ce qui est clair et peu saturé — cheveux gris,
blanc d'une tasse, reflets — passait pour du fond et était effacé ou amputé.
Les originaux n'ont pas besoin de ça : ils sont déjà sur fond blanc.

Ici rien n'est détecté, filtré ni effacé. Pour chaque original :
  1. on rogne 3 px de chaque bord (filet noir d'1 px présent sur les fichiers bruts)
  2. le fond est estimé sur le bord de l'image ; s'il n'est pas blanc (quelques
     originaux sont légèrement gris), un gain global par canal le ramène à 255
  3. recadrage sur la boîte englobante des traits sombres du dessin (+ 3 % de marge) :
     le filigrane « Generated by … » et l'ombre de la carte, clairs, restent dehors
  4. mise à l'échelle (Lanczos) pour que le côté le plus grand occupe 88 % de
     512 px, centré sur fond blanc

    python3 scripts/reprocess_raw.py nainai gongjiaoche
    python3 scripts/reprocess_raw.py --all
    python3 scripts/reprocess_raw.py --all --dry-run --sheet cmp.png
"""
import argparse
import glob
import json
import os

import numpy as np
from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
IMG = os.path.join(ROOT, "assets", "img")
EXTS = (".jpg", ".jpeg", ".png", ".webp")

CANVAS = 512
FILL = 0.88
EDGE = 3              # px rognés sur chaque bord
DIFF = 120            # écart (sur 255) avec le fond : les traits du dessin sont sombres ; le
                      # filigrane et l'ombre de la carte sont clairs et restent hors du cadre
PAD = 0.03            # marge ajoutée autour du cadre, en part du plus grand côté

# Originaux dessinés dans une carte à fin cadre : on recadre À L'INTÉRIEUR du cadre.
IN_CARD = {"kuai", "qian", "shufu", "yu2", "yue", "zuo", "meimei"}
CARD_INSET = 0.04     # part du côté de la carte rognée avant de chercher le dessin

# Mots pour lesquels aucun original ne correspond à l'image publiée : ils ne sont pas refaits par --all.
#  - baise, heise, hongse, lvse : l'image publiée est la « tache de peinture » unifiée (variants/)
#  - yeye : la version publiée n'a pas de brut archivé (seul le premier grand-père l'est)
OTHER_DRAWING = {"baise", "heise", "hongse", "lvse", "yeye"}


def raw_slug(path):
    """« cha__v2.jpg », « shengri__originaux.jpg » et « cha.png » sont des originaux de « cha » / « shengri »."""
    return os.path.splitext(os.path.basename(path))[0].split("__")[0]


def find_raws(raw_dir, slug):
    return sorted(f for f in glob.glob(os.path.join(raw_dir, "hsk*", "*.*"))
                  if f.lower().endswith(EXTS) and raw_slug(f) == slug)


def all_slugs(raw_dir):
    return sorted({raw_slug(f) for f in glob.glob(os.path.join(raw_dir, "hsk*", "*.*"))
                   if f.lower().endswith(EXTS)})


def gray(im):
    return np.asarray(im.convert("L").resize((64, 64), Image.BILINEAR), dtype=float)


def best_crop(raws, slug, current):
    """Recadre chaque original du mot ; garde celui qui ressemble le plus à l'image publiée."""
    best = None
    for f in raws:
        new = crop(Image.open(f), in_card=slug in IN_CARD)
        diff = float(np.abs(gray(new) - gray(current)).mean())
        if best is None or diff < best[0]:
            best = (diff, f, new)
    return best[1], best[2]


def level_of(slug):
    for lvl in (1, 2):
        m = json.load(open(os.path.join(IMG, f"hsk{lvl}", "manifest.json"), encoding="utf-8"))
        if any(w["slug"] == slug for w in m["words"]):
            return lvl
    return None


def crop(raw, in_card=False):
    """raw : image PIL. Retourne l'image 512×512 recadrée, sur fond blanc."""
    a = np.asarray(raw.convert("RGB"), dtype=np.float64)
    a = a[EDGE:-EDGE, EDGE:-EDGE]
    border = np.concatenate([a[:16].reshape(-1, 3), a[-16:].reshape(-1, 3),
                             a[:, :16].reshape(-1, 3), a[:, -16:].reshape(-1, 3)])
    bg = np.median(border, axis=0)
    a = np.clip(a * (255.0 / np.maximum(bg, 1.0)), 0, 255)     # fond -> blanc, rien d'autre ne change

    content = (255 - a).max(axis=2) > DIFF
    ys, xs = np.nonzero(content)
    x0, x1, y0, y1 = xs.min(), xs.max() + 1, ys.min(), ys.max() + 1
    if in_card:                                   # ce premier cadre est celui de la carte : on entre dedans
        m = round(CARD_INSET * max(x1 - x0, y1 - y0))
        inner = content[y0 + m:y1 - m, x0 + m:x1 - m]
        ys, xs = np.nonzero(inner)
        x0, x1, y0, y1 = x0 + m + xs.min(), x0 + m + xs.max() + 1, y0 + m + ys.min(), y0 + m + ys.max() + 1
    pad = round(PAD * max(x1 - x0, y1 - y0))
    x0, y0 = max(0, x0 - pad), max(0, y0 - pad)
    x1, y1 = min(a.shape[1], x1 + pad), min(a.shape[0], y1 + pad)
    im = Image.fromarray(a.astype(np.uint8)).crop((x0, y0, x1, y1))

    scale = CANVAS * FILL / max(im.size)
    im = im.resize((max(1, round(im.width * scale)), max(1, round(im.height * scale))), Image.LANCZOS)
    out = Image.new("RGB", (CANVAS, CANVAS), (255, 255, 255))
    out.paste(im, ((CANVAS - im.width) // 2, (CANVAS - im.height) // 2))
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("slugs", nargs="*")
    ap.add_argument("--all", action="store_true", help="tous les mots qui ont un original")
    ap.add_argument("--exclude", nargs="*", default=[], help="mots à ne pas refaire")
    ap.add_argument("--raw", default=os.path.join(ROOT, "assets", "img-raw"),
                    help="dossier contenant hsk1/ et hsk2/ (défaut : assets/img-raw)")
    ap.add_argument("--dry-run", action="store_true", help="n'écrit rien dans assets/img/")
    ap.add_argument("--sheet", help="planche actuel | refait (PNG)")
    args = ap.parse_args()
    if not args.slugs and not args.all:
        ap.error("indique des mots, ou --all")

    rows = []
    for slug in (all_slugs(args.raw) if args.all else args.slugs):
        if slug in args.exclude or (args.all and slug in OTHER_DRAWING):
            continue
        lvl, raws = level_of(slug), find_raws(args.raw, slug)
        if lvl is None or not raws:
            print(f"{slug:12} ignoré : {'mot inconnu' if lvl is None else 'pas d’original'}")
            continue
        dst = os.path.join(IMG, f"hsk{lvl}", slug + ".webp")
        current = Image.open(dst).convert("RGB")
        src, new = best_crop(raws, slug, current)
        rows.append((slug, current, new))
        print(f"{slug:12} recadré depuis {os.path.basename(src)}")
        if not args.dry_run:
            new.save(dst, "WEBP", quality=90, method=6)
    print(f"{len(rows)} image(s) {'à refaire' if args.dry_run else 'refaite(s)'}")

    if args.sheet and rows:
        T, per = 158, 20
        base, ext = os.path.splitext(args.sheet)
        for si in range(0, len(rows), per):
            sh = Image.new("RGB", (4 * (2 * T + 6), 5 * (T + 16)), (110, 110, 110))
            d = ImageDraw.Draw(sh)
            for k, (slug, old, new) in enumerate(rows[si:si + per]):
                x, y = (k % 4) * (2 * T + 6), (k // 4) * (T + 16)
                sh.paste(old.resize((T, T)), (x, y))
                sh.paste(new.resize((T, T)), (x + T, y))
                d.text((x + 3, y + T + 2), f"{slug}  actuel | refait", fill=(255, 255, 255))
            sh.save(f"{base}{si // per}{ext}")
        print("planches :", f"{base}*{ext}")


if __name__ == "__main__":
    main()
